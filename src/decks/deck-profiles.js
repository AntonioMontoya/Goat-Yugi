/**
 * Resolves the canonical profile for a given deck ID.
 * Normalizes variations (e.g. prefixes or legacy ids).
 */
export function getDeckProfile(deckId = "") {
  const normalized = String(deckId ?? "").trim().toLowerCase();
  if (!normalized) return DEFAULT_DECK_PROFILE;

  if (DECK_PROFILES[normalized]) return DECK_PROFILES[normalized];

  // Try with/without goatformat- prefix
  const withPrefix = normalized.startsWith("goatformat-") ? normalized : `goatformat-${normalized}`;
  if (DECK_PROFILES[withPrefix]) return DECK_PROFILES[withPrefix];

  const withoutPrefix = normalized.replace(/^goatformat-/, "");
  if (DECK_PROFILES[withoutPrefix]) return DECK_PROFILES[withoutPrefix];

  return DEFAULT_DECK_PROFILE;
}
